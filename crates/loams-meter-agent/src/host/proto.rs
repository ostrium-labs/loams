//! `loams.meter.v1.host`: the host-report messages (platform doc 06 §3.1,
//! §3.3; design §63 §21) and their framing on the node-local socket.
//!
//! The schema is `crates/loams-meter-agent/proto/host.proto`; the types here
//! are written by hand with `prost`'s derive, so the agent needs no `protoc`
//! at build time. Each frame is one message, length-delimited (a varint
//! length, then the message), as doc 06 §3.1 specifies.
//!
//! The host writes [`HostMessage`]s and the agent answers with
//! [`AgentMessage`]s:
//!
//! 1. `Hello { host_id, epoch, acked_seq }`: the host's id, the epoch it
//!    already holds when it reconnects (empty on its first connection) and
//!    the last ack it received.
//! 2. `Welcome { epoch, key, acked_seq }`: the agent's epoch and HMAC key
//!    for this host process, and the last sequence number it has durably
//!    recorded, so the host resends only what follows.
//! 3. `HostReport` / `HostReportAck`, `Gap` / `HostReportAck`,
//!    `SandboxFinished` / `SandboxReadAck`.

use prost::Message;
use tokio::io::{AsyncRead, AsyncReadExt, AsyncWrite, AsyncWriteExt};

/// The largest frame either side accepts (16 MiB).
pub const MAX_FRAME: usize = 16 << 20;

/// One invocation's usage, as the host measured it (doc 06 §3.1, §3.2).
#[derive(Clone, PartialEq, Message)]
pub struct Invocation {
    /// The org billed.
    #[prost(string, tag = "1")]
    pub org: String,
    /// The namespace inside the org.
    #[prost(string, tag = "2")]
    pub namespace: String,
    /// The function.
    #[prost(string, tag = "3")]
    pub function: String,
    /// The function's version.
    #[prost(string, tag = "4")]
    pub version: String,
    /// Generated by the host, never by the tenant (PD64).
    #[prost(string, tag = "5")]
    pub invocation_id: String,
    /// CPU microseconds; exact only when `cpu_estimated` is false.
    #[prost(uint64, tag = "6")]
    pub cpu_usec: u64,
    /// wasmtime fuel; 0 when fuel is off.
    #[prost(uint64, tag = "7")]
    pub fuel: u64,
    /// Epoch ticks consumed.
    #[prost(uint64, tag = "8")]
    pub epochs: u64,
    /// Start, Unix milliseconds.
    #[prost(int64, tag = "9")]
    pub start_unix_ms: i64,
    /// End, Unix milliseconds.
    #[prost(int64, tag = "10")]
    pub end_unix_ms: i64,
    /// Whether `cpu_usec` was apportioned rather than measured.
    #[prost(bool, tag = "11")]
    pub cpu_estimated: bool,
    /// The runner; empty means the supervisor.
    #[prost(string, tag = "12")]
    pub runner: String,
}

/// A batch of invocations from one host process (doc 06 §3.1, §3.3).
#[derive(Clone, PartialEq, Message)]
pub struct HostReport {
    /// Stable for the life of the host process.
    #[prost(string, tag = "1")]
    pub host_id: String,
    /// Monotonic per `host_id`, from 1.
    #[prost(uint64, tag = "2")]
    pub seq: u64,
    /// The invocations.
    #[prost(message, repeated, tag = "3")]
    pub invocations: Vec<Invocation>,
    /// The epoch the agent gave this host process (16 bytes, PD64).
    #[prost(bytes = "vec", tag = "4")]
    pub epoch: Vec<u8>,
    /// `HMAC-SHA-256(key, host_id ‖ epoch ‖ seq ‖ canonical(invocations))`.
    #[prost(bytes = "vec", tag = "5")]
    pub mac: Vec<u8>,
}

/// Reports the host dropped or lost (doc 06 §3.3): every `seq` in
/// `from_seq..=to_seq` will never arrive.
#[derive(Clone, PartialEq, Message)]
pub struct Gap {
    /// The host.
    #[prost(string, tag = "1")]
    pub host_id: String,
    /// The first missing `seq`.
    #[prost(uint64, tag = "2")]
    pub from_seq: u64,
    /// The last missing `seq`.
    #[prost(uint64, tag = "3")]
    pub to_seq: u64,
    /// Why: `buffer_full`, `spool_full` or `spool_lost`.
    #[prost(string, tag = "4")]
    pub reason: String,
    /// The epoch, as on reports.
    #[prost(bytes = "vec", tag = "5")]
    pub epoch: Vec<u8>,
    /// `HMAC-SHA-256(key, "gap" ‖ host_id ‖ epoch ‖ from_seq ‖ to_seq ‖ reason)`.
    #[prost(bytes = "vec", tag = "6")]
    pub mac: Vec<u8>,
}

/// A sandbox's last process exited; the host removes its cgroup only after
/// the agent's [`SandboxReadAck`] (doc 06 §3.0).
#[derive(Clone, PartialEq, Message)]
pub struct SandboxFinished {
    /// The cgroup, relative to the cgroup root.
    #[prost(string, tag = "1")]
    pub cgroup: String,
}

/// The host's handshake.
#[derive(Clone, PartialEq, Message)]
pub struct Hello {
    /// The host process's id.
    #[prost(string, tag = "1")]
    pub host_id: String,
    /// The epoch the host holds from an earlier connection, or empty.
    #[prost(bytes = "vec", tag = "2")]
    pub epoch: Vec<u8>,
    /// The last ack the host received (0 if none). A fresh session starts
    /// there, so reports an earlier agent boot recorded are not resent and
    /// are not mistaken for a gap.
    #[prost(uint64, tag = "3")]
    pub acked_seq: u64,
}

/// The agent's handshake reply.
#[derive(Clone, PartialEq, Message)]
pub struct Welcome {
    /// 16 random bytes, new for every host process and every agent boot.
    #[prost(bytes = "vec", tag = "1")]
    pub epoch: Vec<u8>,
    /// The 32-byte HMAC key for this epoch.
    #[prost(bytes = "vec", tag = "2")]
    pub key: Vec<u8>,
    /// Every report of this host up to this `seq` is durably recorded.
    #[prost(uint64, tag = "3")]
    pub acked_seq: u64,
}

/// Cumulative: every report (and gap) with `seq <= this` is recorded.
#[derive(Clone, PartialEq, Message)]
pub struct HostReportAck {
    /// The highest `seq` covered.
    #[prost(uint64, tag = "1")]
    pub seq: u64,
}

/// The agent has read the finished sandbox's final counters.
#[derive(Clone, PartialEq, Message)]
pub struct SandboxReadAck {
    /// The cgroup, as in [`SandboxFinished`].
    #[prost(string, tag = "1")]
    pub cgroup: String,
}

/// The agent refused a message; the connection closes after it.
#[derive(Clone, PartialEq, Message)]
pub struct Reject {
    /// `unknown_epoch`, `bad_mac`, `seq_gap`, `peer_not_allowed`, ….
    #[prost(string, tag = "1")]
    pub reason: String,
}

/// What a host sends.
#[derive(Clone, PartialEq, Message)]
pub struct HostMessage {
    /// The message.
    #[prost(oneof = "HostMsg", tags = "1, 2, 3, 4")]
    pub msg: Option<HostMsg>,
}

/// [`HostMessage`]'s variants.
#[derive(Clone, PartialEq, prost::Oneof)]
pub enum HostMsg {
    /// The handshake.
    #[prost(message, tag = "1")]
    Hello(Hello),
    /// A batch.
    #[prost(message, tag = "2")]
    Report(HostReport),
    /// Dropped reports.
    #[prost(message, tag = "3")]
    Gap(Gap),
    /// A finished sandbox.
    #[prost(message, tag = "4")]
    SandboxFinished(SandboxFinished),
}

/// What the agent sends.
#[derive(Clone, PartialEq, Message)]
pub struct AgentMessage {
    /// The message.
    #[prost(oneof = "AgentMsg", tags = "1, 2, 3, 4")]
    pub msg: Option<AgentMsg>,
}

/// [`AgentMessage`]'s variants.
#[derive(Clone, PartialEq, prost::Oneof)]
pub enum AgentMsg {
    /// The handshake reply.
    #[prost(message, tag = "1")]
    Welcome(Welcome),
    /// A cumulative ack.
    #[prost(message, tag = "2")]
    Ack(HostReportAck),
    /// A final read is done.
    #[prost(message, tag = "3")]
    SandboxRead(SandboxReadAck),
    /// A refusal.
    #[prost(message, tag = "4")]
    Reject(Reject),
}

/// Writes `msg` as one length-delimited frame.
pub async fn write_frame<W, M>(w: &mut W, msg: &M) -> std::io::Result<()>
where
    W: AsyncWrite + Unpin,
    M: Message,
{
    let buf = msg.encode_length_delimited_to_vec();
    w.write_all(&buf).await?;
    w.flush().await
}

/// Reads one length-delimited frame. `Ok(None)` at a clean end of stream.
pub async fn read_frame<R, M>(r: &mut R) -> std::io::Result<Option<M>>
where
    R: AsyncRead + Unpin,
    M: Message + Default,
{
    let mut len: u64 = 0;
    let mut shift = 0u32;
    loop {
        let mut byte = [0u8; 1];
        let n = r.read(&mut byte).await?;
        if n == 0 {
            if shift == 0 {
                return Ok(None);
            }
            return Err(std::io::ErrorKind::UnexpectedEof.into());
        }
        len |= u64::from(byte[0] & 0x7f) << shift;
        if byte[0] & 0x80 == 0 {
            break;
        }
        shift += 7;
        if shift >= 64 {
            return Err(invalid("frame length varint too long"));
        }
    }
    let len = usize::try_from(len).map_err(|_| invalid("frame too large"))?;
    if len > MAX_FRAME {
        return Err(invalid("frame too large"));
    }
    let mut buf = vec![0u8; len];
    r.read_exact(&mut buf).await?;
    M::decode(buf.as_slice())
        .map(Some)
        .map_err(|e| invalid(&e.to_string()))
}

fn invalid(message: &str) -> std::io::Error {
    std::io::Error::new(std::io::ErrorKind::InvalidData, message.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn frames_round_trip() {
        let (mut a, mut b) = tokio::io::duplex(1 << 16);
        let msg = HostMessage {
            msg: Some(HostMsg::Report(HostReport {
                host_id: "h1".into(),
                seq: 7,
                invocations: vec![Invocation {
                    org: "org_a".into(),
                    cpu_usec: 1500,
                    ..Invocation::default()
                }],
                epoch: vec![1; 16],
                mac: vec![2; 32],
            })),
        };
        write_frame(&mut a, &msg).await.unwrap();
        drop(a);
        let back: HostMessage = read_frame(&mut b).await.unwrap().unwrap();
        assert_eq!(back, msg);
        let end: Option<HostMessage> = read_frame(&mut b).await.unwrap();
        assert!(end.is_none());
    }
}
