def write_stubs(root: Path, protoc: str) -> int:
    """Runs protoc into ``src/`` and writes the ``__init__.py`` files it omits."""
    destination = root / STUB_ROOT
    subprocess.run(  # noqa: S603
        [
            protoc,
            f"-I{PROTO_DIR}",
            f"--python_out={STUB_ROOT}",
            f"--pyi_out={STUB_ROOT}",
            *sorted(str(path.relative_to(root)) for path in (root / PROTO_DIR).rglob("*.proto")),
        ],
        cwd=root,
        check=True,
    )
    written = 0
    for path in sorted((destination / "loams").rglob("*_pb2.py")):
        directory = path.parent
        init = directory / "__init__.py"
        if init.exists():
            continue
        dotted = ".".join(directory.relative_to(destination).parts)
        init.write_text(INIT_MARKER.format(path=dotted), encoding="utf-8")
        written += 1
    for path in sorted((destination / "loams").rglob("*_pb2.pyi")):
        directory = path.parent
        init = directory / "__init__.pyi"
        if not init.exists():
            init.write_text("", encoding="utf-8")
            written += 1
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="the repository root")
    parser.add_argument("--protoc", default="protoc", help="the protoc to run")
    parser.add_argument(
        "--skip-stubs",
        action="store_true",
        help="render facade.py without regenerating the protobuf stubs",
    )
    arguments = parser.parse_args(argv)

    root = Path(arguments.root).resolve()
    sys.path.insert(0, str(root / STUB_ROOT))
    load_extensions(root)

    if not arguments.skip_stubs:
        count = write_stubs(root, arguments.protoc)
        print(f"wrote the protobuf stubs and {count} __init__ files under {STUB_ROOT}/loams")

    descriptor_set = read_descriptor_set(root, arguments.protoc)
    reasons = parse_reasons(
        (root / REASONS_PAGE).read_text(encoding="utf-8"), root / REASONS_PAGE
    )
    model = build_model(descriptor_set, reasons)
    out = root / FACADE_OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(model), encoding="utf-8")
    print(f"wrote {FACADE_OUT}: {len(model.modules)} modules, {len(model.reasons)} reasons")
    for module in model.modules:
        print(f"  {module.name}: " + ", ".join(f"{call.name}({call.retry})" for call in module.calls))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
