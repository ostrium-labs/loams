def parse_reasons(text: str, path: Path) -> tuple[Reason, ...]:
    """The registry page, with the same row shape ``reasons.rs`` validates."""
    out: list[Reason] = []
    seen: set[str] = set()
    for number, line in enumerate(text.splitlines(), start=1):
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        cells = [cell.strip() for cell in stripped.strip("|").split("|")]
        if len(cells) < 2:
            continue
        # `reasons.rs` only accepts a row whose first cell is a backticked
        # reason, which is what skips the header and the `|---|` separator.
        if not cells[0].startswith("`"):
            continue
        reason = cells[0].strip("`")
        code = cells[1].strip("`")
        if not reason or not code:
            continue
        if not all(character.islower() or character.isdigit() or character == "_" for character in reason):
            raise SystemExit(f"{path}:{number}: {reason!r} is not lower_snake_case")
        if reason in seen:
            raise SystemExit(f"{path}:{number}: {reason!r} is registered twice")
        seen.add(reason)
        out.append(Reason(reason=reason, code=code))
    if not out:
        raise SystemExit(f"{path}: no registry rows found")
    return tuple(out)


def build_model(descriptor_set: Any, reasons: tuple[Reason, ...]) -> Model:
    """The modules and the reason registry, from the two inputs as Rust reads them."""
    from loams.options.v1 import options_pb2

    module_option = options_pb2.module
    facade_option = options_pb2.facade

    modules: dict[str, dict[str, Any]] = {}
    packages: list[str] = []
    for file_proto in descriptor_set.file:
        package = file_proto.package
        if not package:
            continue
        packages.append(package)
        for service in file_proto.service:
            if not service.options.HasExtension(module_option):
                continue
            declared = service.options.Extensions[module_option]
            for method in service.method:
                for facade in method.options.Extensions[facade_option]:
                    name = facade.module or declared.name
                    derived = name != declared.name
                    entry = modules.get(name)
                    if entry is None:
                        entry = {
                            "name": name,
                            "summary": "" if derived else declared.summary,
                            "unstable": declared.unstable,
                            "service": f"{package}.{service.name}",
                            "package": package,
                            "derived": derived,
                            "calls": [],
                        }
                        modules[name] = entry
                    entry["calls"].append(
                        _call(package, service.name, method, facade, name)
                    )

    ordered: list[Module] = []
    for name in sorted(modules):
        entry = modules[name]
        calls = sorted(entry["calls"], key=lambda call: call.name)
        ordered.append(
            Module(
                name=entry["name"],
                summary=entry["summary"],
                unstable=entry["unstable"],
                service=entry["service"],
                package=entry["package"],
                derived=entry["derived"],
                calls=tuple(calls),
            )
        )
    return Model(
        modules=tuple(ordered),
        reasons=reasons,
        packages=tuple(sorted(set(packages))),
    )


def _is_set(message: Any, number: int) -> bool:
    """Whether a proto3 scalar was written at all.

    `FacadeOptions.retry_safe` is a proto3 `bool` with no presence, so Python's
    `HasField` refuses it. `ListFields` is the same answer `lib.rs` gets by
    finding field 3 in the wire bytes, and it is the distinction that matters:
    an *unset* `retry_safe` must not read as "false, so never retry".
    """
    return any(field.number == number for field, _ in message.ListFields())


def _call(
    package: str,
    service_name: str,
    method: Any,
    facade: Any,
    module_name: str,
) -> Call:
    idempotency = IDEMPOTENCY_NAMES.get(method.options.idempotency_level, "none")
    # D610: reads and idempotent RPCs retry on their own; a mutation retries only
    # when the caller gave it an idempotency key. `retry_safe` overrides both
    # ways, which is why an unset option must not read as "false".
    if _is_set(facade, 3):
        retry = "safe" if facade.retry_safe else "manual"
    else:
        retry = RETRY_SAFE_BY_IDEMPOTENCY[idempotency]
    return Call(
        module=module_name,
        name=facade.name or method.name,
        method=method.name,
        input=method.input_type.lstrip("."),
        output=method.output_type.lstrip("."),
        service=f"{package}.{service_name}",
        package=package,
        idempotency=idempotency,
        retry=retry,
        streaming="server" if method.server_streaming else "unary",
        pagination=_pagination(package, service_name, facade.pagination),
    )


def _pagination(package: str, service: str, raw: str) -> Pagination | None:
    if not raw:
        return None
    where = f"{package}.{service}"
    if ":" not in raw:
        raise SystemExit(f'{where}: expected "<items field>:<next page token field>"')
    items, token = raw.split(":", 1)
    if not items or not token:
        raise SystemExit(f"{where}: one of the two field names is empty")
    return Pagination(items=items, next_page_token=token)


def load_extensions(root: Path) -> None:
    """Imports ``loams.options.v1``, which is what defines the two extensions.

    **This must happen before the descriptor set is parsed.** upb decides an
    unknown field's meaning while it parses, from the extension registry the pool
    holds *at that moment*; an extension whose file has not been added yet is not
    recognised and the field stays in unknown fields, so ``HasExtension`` answers
    False forever after and every module silently disappears. Importing first is
    the whole fix; the order is load-bearing, so it is a function with a name
    rather than an incidental import.
    """
    from loams.options.v1 import options_pb2  # noqa: F401


def read_descriptor_set(root: Path, protoc: str) -> Any:
    """The descriptor set of ``proto/``, which is what ``buf`` hands the plugin."""
    import tempfile

    protos = sorted(str(path.relative_to(root)) for path in (root / PROTO_DIR).rglob("*.proto"))
    if not protos:
        raise SystemExit(f"{PROTO_DIR}/ has no .proto files")
    with tempfile.TemporaryDirectory() as directory:
        out = Path(directory) / "descriptor.bin"
        subprocess.run(  # noqa: S603
            [
                protoc,
                f"-I{PROTO_DIR}",
                f"--include_imports",
                f"--descriptor_set_out={out}",
                *protos,
            ],
            cwd=root,
            check=True,
        )
        descriptor_set = descriptor_pb2.FileDescriptorSet()
        descriptor_set.ParseFromString(out.read_bytes())
    return descriptor_set


