def python_path(proto_name: str) -> str:
    """``loams.instance.v1.GetInstanceRequest`` → ``loams.instance.v1.instance_pb2``."""
    package, _, message = proto_name.rpartition(".")
    return f"{package}.{package.rsplit('.', 1)[-1]}_pb2.{message}"


def stub_module(proto_name: str) -> str:
    """The module a message type is imported from."""
    package = proto_name.rpartition(".")[0]
    return f"{package}.{package.rsplit('.', 1)[-1]}_pb2"


def render(model: Model) -> str:
    imports: set[str] = set()
    for module in model.modules:
        for call in module.calls:
            imports.add(python_path(call.input))
            imports.add(python_path(call.output))

    render_modules: list[str] = []
    typed: list[str] = []
    methods: list[str] = []
    module_names: list[str] = []

    for module in model.modules:
        class_name = "".join(part.title() for part in module.name.split(".")) + "Module"
        module_names.append(f'"{class_name}"')
        render_modules.append(_render_module(module))
        typed.append(_render_typed_module(module, class_name))
        for call in module.calls:
            methods.append(
                f'    "{call.rpc}": MethodInfo(\n'
                f'        name="{call.method}",\n'
                f'        service_name="{call.service}",\n'
                f'        input={python_path(call.input)},\n'
                f'        output={python_path(call.output)},\n'
                f'        idempotency_level=IDEMPOTENCY_LEVELS["{call.idempotency}"],\n'
                f"    ),"
            )

    values = {
        "IMPORTS": "\n".join(
            "from {} import {}".format(path.rsplit(".", 1)[0], path.rsplit(".", 1)[1])
            for path in sorted(imports)
        ),
        "PROTO_REV": PROTO_REV,
        "MODULES": "\n".join(render_modules),
        "PACKAGES": "\n".join(f'    "{name}",' for name in model.packages),
        "REASONS": "\n".join(f'    "{reason.reason}",' for reason in model.reasons),
        "REASON_LITERALS": "\n".join(f'    "{reason.reason}",' for reason in model.reasons),
        "CODES": "\n".join(f'    "{reason.reason}": "{reason.code}",' for reason in model.reasons),
        "MODULES_TYPED": "\n\n".join(typed),
        "METHODS": "\n".join(methods),
        "MODULE_NAMES": ", ".join(module_names),
    }
    out = HEADER
    for name, value in values.items():
        out = out.replace(f"@@{name}@@", value)
    return out


def _render_module(module: Module) -> str:
    lines = ["    ModuleBinding(", f'        name="{module.name}",', f'        summary="{module.summary}",', f'        service="{module.service}",', f'        package="{module.package}",', f"        unstable={module.unstable!r},", f"        derived={module.derived!r},", "        calls=("]
    for call in module.calls:
        pagination = (
            "None"
            if call.pagination is None
            else f"Pagination(items=\"{call.pagination.items}\", "
            f"next_page_token=\"{call.pagination.next_page_token}\")"
        )
        lines.append(
            "            _binding(\n"
            f'                "{call.module}",\n'
            f'                "{call.name}",\n'
            f'                "{call.method}",\n'
            f'                "{call.rpc}",\n'
            f'                "{call.service}",\n'
            f'                "{call.package}",\n'
            f'                "{call.idempotency}",\n'
            f'                "{call.retry}",\n'
            f'                "{call.streaming}",\n'
            f"                {pagination},\n"
            "            ),"
        )
    lines.append("        ),")
    lines.append("    ),")
    return "\n".join(lines)


def _render_typed_module(module: Module, class_name: str) -> str:
    """One typed module, as a ``Protocol``.

    A ``Protocol`` is the Python translation of what ``typescript.rs`` emits as an
    ``interface``: the *shape* of a module, with the generated message types on
    every signature, and no implementation. Both clients satisfy it structurally,
    so the same description types the sync and the async client and neither has to
    be written twice.

    A server-streaming call is declared as returning either iterator type, because
    which one you get is decided by the client you built rather than by the proto:
    a narrower return on the implementation is still a valid implementation.
    """
    lines = [
        f"class {class_name}(Protocol):",
        f'    """``loams.{module.name}`` — {module.summary or module.service}',
        "",
        f'    Wraps ``{module.service}``.'
        + (
            " Its wire contract may still change, so `buf breaking` skips it and the"
            " SDK marks it experimental (§44 §10.3)."
            if module.unstable
            else ""
        ),
        '    """',
        "",
        "    #: The SDK module, as it appears on the client object.",
        "    module: str",
        "    #: The service behind the module.",
        "    service: str",
        "    #: Whether the package's wire contract may still change.",
        "    unstable: bool",
    ]
    for call in module.calls:
        lines.append("")
        lines.extend(_render_typed_call(call))
    lines.append("")
    lines.append("")
    lines.append("")
    return "\n".join(lines).rstrip()


def _render_typed_call(call: Call) -> list[str]:
    request = python_path(call.input)
    response = python_path(call.output)
    returns = f"Iterator[{response}] | AsyncIterator[{response}]"
    if call.streaming != "server":
        returns = response
    return [
        "    def " + call.name + "(",
        "        self,",
        f"        request: {request},",
        "        options: CallOptions | None = None,",
        f"    ) -> {returns}:",
        f'        """``{call.rpc}``, retried: {call.retry}."""',
        "        ...",
    ]


