#!/usr/bin/env python3
"""Generate ``sdks/python/src/loams/gen/facade.py``, and the protobuf stubs beside it.

This is the **bootstrap** generator for the Python SDK (design §44 §7.3, D606).

The real one is ``protoc-gen-loams-facade`` with ``opt: lang=python``, owned by
SDK1 Task 3 and rendered from ``sdks/templates/python/``. **It does not exist
yet**, so this script stands in for it: it reads the same two inputs the Rust
plugin reads — a descriptor set built from ``proto/`` and the reason registry in
``docs/api/reasons.md`` — applies the same model
(``crates/loams-facade-gen/src/lib.rs``), and writes the same table the
hand-written runtime dispatches through.

Two things come out of it:

``sdks/python/src/loams/<proto package>/**/*_pb2.py``
    the ``protoc-gen-python`` stubs. protoc's Python plugin does not emit
    ``__init__.py`` files and a wheel needs them for the subpackages to be
    importable, so this script writes them. That is packaging scaffolding, not
    generated code: no generated file is edited.

``sdks/python/src/loams/gen/facade.py``
    the binding table: ``PROTO_REV``, ``MODULES``, ``PROTO_PACKAGES``,
    ``REASONS``, ``REASON_CODES``, ``FEATURE_NOT_IN_VARIANT``, and the typed
    module classes.

Run it with the repository root as the working directory::

    python sdks/python/tools/bootstrap_facade.py

**When ``lang=python`` lands, delete this script and run
``scripts/sdk/gen.sh python`` instead.** Nothing in ``src/loams/runtime`` reads
this file's provenance; it reads the same table either way, so the swap is a
regeneration and a diff.

Why the stubs land inside the ``loams`` package rather than beside it: protoc
writes imports that are absolute in the proto tree (``from loams.live.v1 import
value_pb2``), because the proto package *is* called ``loams``. Emitting into
``src/`` therefore puts them at ``loams.<proto package>``, which is both what
the generated code imports and the package name design §44 §9 row 2 reserves.
"""

