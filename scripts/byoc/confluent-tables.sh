#!/usr/bin/env bash
# The Confluent Cloud region and price tables (plan CC1 Task 5, design 80 §6.1, D1824).
#
#   confluent-tables.sh refresh [--from <env_metadata.json>]
#       Rewrites deploy/byoc/confluent/regions.toml from Confluent's region listing,
#       GET https://confluent.cloud/api/env_metadata (what `confluent kafka region
#       list` calls; undocumented, CC0 ruling R0.4), with the Cloud API key in
#       CONFLUENT_CLOUD_API_KEY / CONFLUENT_CLOUD_API_SECRET. Keeps only cloud,
#       region, schedulable and the cluster types. --from reads a saved response
#       instead (tests). Prints nothing secret. Exit 4: the response's shape changed.
#   confluent-tables.sh check [--max-age-days N]
#       Offline: both tables parse; the BY1 default regions offer Basic and
#       Standard; every price has a source and a read date; prices.toml was read
#       within N days (default 90). Exit 1 on a failure.
#   confluent-tables.sh diff [--from <env_metadata.json>]
#       refresh into a temporary file and compare with the committed table.
#       Exit 0: same; 3: the region list changed (the weekly job opens a PR).
#   confluent-tables.sh gen
#       Writes deploy/tofu/modules/confluent/confluent-tables.json, the copy of both
#       tables the OpenTofu module reads (OpenTofu has no TOML decoder). refresh
#       runs it too; check fails when the copy is not current.
#
# prices.toml is edited by hand, each value with its source URL and read date.
# Needs bash, curl, jq and python3 (>= 3.11, for tomllib).
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
tables="${CONFLUENT_TABLES_DIR:-$repo/deploy/byoc/confluent}"
url="${CONFLUENT_ENV_METADATA_URL:-https://confluent.cloud/api/env_metadata}"
today="${CONFLUENT_TABLES_TODAY:-$(date -u +%F)}"
module_json="${CONFLUENT_TABLES_MODULE_JSON:-$repo/deploy/tofu/modules/confluent/confluent-tables.json}"

die() { echo "confluent-tables: $*" >&2; exit "${2:-1}"; }

fetch() {  # $1 = output file
  : "${CONFLUENT_CLOUD_API_KEY:?CONFLUENT_CLOUD_API_KEY is not set}"
  : "${CONFLUENT_CLOUD_API_SECRET:?CONFLUENT_CLOUD_API_SECRET is not set}"
  local code
  # The key goes to curl on stdin, never in argv or a log.
  code="$(printf 'user = "%s:%s"\n' "$CONFLUENT_CLOUD_API_KEY" "$CONFLUENT_CLOUD_API_SECRET" |
    curl -K - --silent --show-error --proto '=https' --tlsv1.2 --max-time 60 --retry 3 \
      --output "$1" --write-out '%{http_code}' "$url")" || die "the region listing did not answer"
  [[ "$code" == 200 ]] || die "the region listing answered HTTP $code"
}

# render JSON (env_metadata) -> TOML on stdout
render() {
  local src="$1"
  jq -e '(.clouds | type == "array") and ([.clouds[].regions[]] | length > 0)
         and all(.clouds[].regions[]; (.id | type == "string") and (.cloud | type == "string") and (.is_schedulable | type == "boolean") and ((.type // []) | type == "array"))' \
    "$src" >/dev/null || die "the region listing's shape changed (expected .clouds[].regions[] with id, cloud, is_schedulable, type[])" 4
  cat <<EOF
# Confluent Cloud regions and the cluster types each offers (design 80 §6.1, D1824).
# Generated by scripts/byoc/confluent-tables.sh refresh; do not edit by hand.
# Source: $url (undocumented; CC0 ruling R0.4).
# Fallback for a manual refresh: https://docs.confluent.io/cloud/current/clusters/regions.html
# schedulable = false means Confluent lists the region but will not place a cluster there.

schema = 1
read = "$today"
source = "$url"

EOF
  jq -r '
    [.clouds[] as $c | $c.regions[] | {
      cloud: ($c.id | ascii_downcase),
      region: .id,
      schedulable: .is_schedulable,
      types: ([(.type // [])[] | .name | ascii_downcase | select(. != "unknown")] | unique)
    }] | sort_by(.cloud, .region) | .[] |
    "[[region]]\ncloud = \"\(.cloud)\"\nregion = \"\(.region)\"\nschedulable = \(.schedulable)\ntypes = [\(.types | map("\"" + . + "\"") | join(", "))]\n"' "$src"
}

# both tables -> the module's JSON copy on stdout (stable, sorted, two-space indent)
gen_json() {
  python3 -I - "$tables/regions.toml" "$tables/prices.toml" <<'EOP'
import json, sys, tomllib
regions = tomllib.load(open(sys.argv[1], "rb"))
prices = tomllib.load(open(sys.argv[2], "rb"))
out = {
    "_comment": "Generated by scripts/byoc/confluent-tables.sh gen from deploy/byoc/confluent/{regions,prices}.toml; do not edit.",
    "regions_read": str(regions["read"]),
    "prices_read": str(prices["read"]),
    "prices_source": prices["source"],
    "storage_replication_factor": prices["storage_replication_factor"],
    "types": {t: {k: v for k, v in p.items() if not isinstance(v, str)} for t, p in prices["types"].items()},
    "regions": {f'{r["cloud"]}/{r["region"]}': {"schedulable": r["schedulable"], "types": r["types"]} for r in regions["region"]},
}
print(json.dumps(out, indent=2, sort_keys=True))
EOP
}

refresh_to() {  # $1 = destination, $2 = optional --from file
  local work src
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' RETURN
  if [[ -n "${2:-}" ]]; then src="$2"; else src="$work/env_metadata.json"; fetch "$src"; fi
  render "$src" >"$work/regions.toml"
  mv "$work/regions.toml" "$1"
}

check() {
  local max_age="$1"
  python3 -I - "$tables/regions.toml" "$tables/prices.toml" "$today" "$max_age" <<'PY'
import datetime, sys, tomllib

regions_path, prices_path, today, max_age = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
fail = False
def bad(msg):
    global fail
    fail = True
    print(f"FAIL {msg}")
def ok(msg):
    print(f"ok   {msg}")

with open(regions_path, "rb") as f:
    regions = tomllib.load(f)
with open(prices_path, "rb") as f:
    prices = tomllib.load(f)

rows = {(r["cloud"], r["region"]): r for r in regions.get("region", [])}
# regions_cover_by1_defaults: BY1's default regions, one per cloud
for cloud, region in (("aws", "us-east-1"), ("gcp", "us-central1"), ("azure", "eastus")):
    r = rows.get((cloud, region))
    if r is None:
        bad(f"regions_cover_by1_defaults: {cloud} {region} is missing")
    elif not r["schedulable"] or not {"basic", "standard"} <= set(r["types"]):
        bad(f"regions_cover_by1_defaults: {cloud} {region} does not offer basic and standard")
if not fail:
    ok("regions_cover_by1_defaults")
for (cloud, region), r in rows.items():
    if cloud not in ("aws", "gcp", "azure") or not set(r["types"]) <= {"basic", "standard", "enterprise", "dedicated", "freight"}:
        bad(f"regions_well_formed: {cloud} {region} {r['types']}")

# prices_have_source_and_date
before = fail
for key in ("source", "read", "currency", "storage_replication_factor"):
    if key not in prices:
        bad(f"prices_have_source_and_date: prices.toml has no top-level {key}")
types = prices.get("types", {})
for t in ("basic", "standard"):
    if t not in types:
        bad(f"prices_have_source_and_date: no [types.{t}]")
for t, p in types.items():
    for key in ("ecku_hour_usd", "free_ecku", "in_gb_usd", "out_gb_usd", "storage_gb_month_usd",
                "partitions_per_ecku", "partitions_max", "max_ecku", "source", "read"):
        if key not in p:
            bad(f"prices_have_source_and_date: [types.{t}] has no {key}")
    for key in ("ecku_hour_usd", "in_gb_usd", "out_gb_usd", "storage_gb_month_usd"):
        v = p.get(key)
        if v is not None and (not isinstance(v, (int, float)) or v < 0):
            bad(f"prices_have_source_and_date: [types.{t}].{key} is not a price")
    src = p.get("source", prices.get("source", ""))
    if not str(src).startswith("https://"):
        bad(f"prices_have_source_and_date: [types.{t}] source is not a URL")
if fail == before:
    ok("prices_have_source_and_date")

# prices_are_fresh
def as_date(v):
    return v if isinstance(v, datetime.date) else datetime.date.fromisoformat(str(v))
age = (as_date(today) - as_date(prices.get("read", "1970-01-01"))).days
worst = max([age] + [(as_date(today) - as_date(p["read"])).days for p in types.values() if "read" in p])
if worst > max_age:
    bad(f"prices_are_fresh: prices.toml was read {worst} days ago (limit {max_age}); re-read the pricing page and update the read dates")
else:
    ok(f"prices_are_fresh ({worst} days old, limit {max_age})")
sys.exit(1 if fail else 0)
PY
}

cmd="${1:-}"; shift || true
from=""; max_age=90
while [[ $# -gt 0 ]]; do
  case "$1" in
    --from) from="${2:?--from needs a file}"; shift 2 ;;
    --max-age-days) max_age="${2:?--max-age-days needs a number}"; shift 2 ;;
    *) die "unknown argument $1" 2 ;;
  esac
done
[[ "$max_age" =~ ^[0-9]+$ ]] || die "--max-age-days is a number" 2

case "$cmd" in
  refresh)
    refresh_to "$tables/regions.toml" "$from"
    echo "confluent-tables: wrote $tables/regions.toml"
    if [[ -d "$(dirname "$module_json")" ]]; then gen_json >"$module_json"; echo "confluent-tables: wrote $module_json"; fi
    ;;
  gen)
    gen_json >"$module_json"
    echo "confluent-tables: wrote $module_json"
    ;;
  diff)
    work="$(mktemp -d)"
    trap 'rm -rf "$work"' EXIT
    refresh_to "$work/regions.toml" "$from"
    # the read date always changes; compare the rows only
    if diff <(grep -v '^read = ' "$tables/regions.toml") <(grep -v '^read = ' "$work/regions.toml"); then
      echo "confluent-tables: the region list is unchanged"
    else
      echo "confluent-tables: the region list changed"
      exit 3
    fi
    ;;
  check)
    rc=0
    check "$max_age" || rc=1
    if [[ -f "$module_json" ]]; then
      if diff <(gen_json) "$module_json" >/dev/null; then
        echo "ok   module_copy_is_current"
      else
        echo "FAIL module_copy_is_current: run scripts/byoc/confluent-tables.sh gen"; rc=1
      fi
    fi
    exit "$rc"
    ;;
  *) die "usage: confluent-tables.sh refresh|diff [--from file] | check [--max-age-days N] | gen" 2 ;;
esac
