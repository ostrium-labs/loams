"""ClickHouse type-rule cases for the Rust engine (plan HE1 Task 24, D1804).

Writes `conformance/clickhouse/oracle/corpus/he1/24/`: a `setup.sql` with one
table per family (numbers, decimals, dates and times, strings and enums,
nullables) and about 400 cases, one query each: every pair of number types
under `+ - * /`, `%` and `intDiv` (integers), and the six comparisons, plus
decimals, dates and times, string constants compared with typed columns,
boolean contexts, supertypes (`CASE`, `UNION`, `if`, `coalesce`, arrays),
literal types and `Nullable`. Each output column's type in the oracle's
`JSONCompactEachRowWithNamesAndTypes` header is the expression's
`toTypeName` (R23.3), so the oracle checks the type and the value of every
`a op b`.

    scripts/house/gen-type-cases.py               # writes the corpus
    scripts/house/gen-type-cases.py --fixture     # also captures the unit
                                                  # test's fixture from the
                                                  # oracle on 127.0.0.1:28123

`--fixture` writes `fabric/crates/loams-house-engine/tests/fixtures/
type_rules.tsv`: constant expressions (`CAST(v AS T) op CAST(w AS U)`) with
the oracle's answer (types and rows, as JSON), which
`arithmetic_result_types_match_the_oracle` checks without the oracle.
"""

