def query(sql, fmt):
    req = urllib.request.Request(
        f"http://127.0.0.1:28123/?default_format={fmt}",
        data=sql.encode(),
        headers={"Authorization": "Basic " + base64.b64encode(b"oracle:oracle").decode()},
    )
    try:
        return urllib.request.urlopen(req).read().decode()
    except urllib.error.HTTPError as e:
        return "ERROR " + e.headers.get("X-ClickHouse-Exception-Code", "?")


# Constant operands of each type for the fixture.
CONSTS = {
    "UInt8": ["255", "7"], "UInt16": ["65535", "300"], "UInt32": ["4294967295", "70000"],
    "UInt64": ["18446744073709551615", "5000000000"], "Int8": ["-128", "127"],
    "Int16": ["-32768", "-300"], "Int32": ["-2147483648", "2147483647"],
    "Int64": ["-9223372036854775808", "-5000000000"], "Float32": ["-1.5", "2.25"],
    "Float64": ["12345.75", "-3.5"],
}


def fixture():
    lines = []
    types = list(CONSTS)
    for a in types:
        for b in types:
            for i in range(2):
                x = f"CAST({CONSTS[a][i]} AS {a})"
                y = f"CAST({CONSTS[b][1 - i]} AS {b})"
                ops = ["+", "-", "*", "/", "=", "<"]
                if not a.startswith("Float") and not b.startswith("Float"):
                    ops.append("%")
                for op in ops:
                    sql = f"SELECT {x} {op} {y}"
                    body = query(sql, "JSONCompactEachRowWithNamesAndTypes")
                    if body.startswith("ERROR"):
                        continue
                    rows = body.strip().split("\n")[1:]
                    lines.append(sql + "\t" + "\t".join(rows))
    with open(FIXTURE, "w") as f:
        f.write("# Generated by scripts/house/gen-type-cases.py --fixture from clickhouse-server 26.9.2.8:\n")
        f.write("# the query, then the oracle's JSONCompactEachRowWithNamesAndTypes types line and rows.\n")
        for line in lines:
            f.write(line + "\n")
    print(f"{len(lines)} fixture lines in {FIXTURE}")


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(os.path.join(OUT, "cases"))
    with open(os.path.join(OUT, "setup.sql"), "w") as f:
        f.write(SETUP)
    cs = cases()
    for name, sql in cs.items():
        with open(os.path.join(OUT, "cases", name + ".sql"), "w") as f:
            f.write(sql)
    print(f"{len(cs)} cases in {OUT}")
    if "--fixture" in sys.argv[1:]:
        fixture()


if __name__ == "__main__":
    main()
